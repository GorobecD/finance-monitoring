def enc(s: str) -> str:
    """Minimal data-URI encoding (much smaller than full percent-encoding)."""
    s = s.replace('"', "'").replace("%", "%25").replace("#", "%23").replace("<", "%3C").replace(">", "%3E")
    return 'url("data:image/svg+xml,' + s + '")'


def svg(body: str, w: int, h: int, extra: str = "") -> str:
    return enc(f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {w} {h}" preserveAspectRatio="xMidYMax slice" {extra}>{body}</svg>')


def tile(body: str, w: int, h: int) -> str:
    return enc(f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}" viewBox="0 0 {w} {h}">{body}</svg>')


def pines(color, base, n, w, hmin, hmax, seed=1):
    import random
    r = random.Random(seed)
    out, x = [], 0
    while x < w:
        h = r.randint(hmin, hmax)
        bw = h * 0.45
        out.append(f'<path d="M{x:.0f} {base} L{x+bw/2:.0f} {base-h} L{x+bw:.0f} {base} Z" fill="{color}"/>')
        x += bw * r.uniform(0.45, 0.8)
    return "".join(out)


def skyline(color, base, w, hmin, hmax, seed=2, windows=None):
    import random
    r = random.Random(seed)
    out, x = [], 0
    while x < w:
        bw = r.randint(30, 80)
        h = r.randint(hmin, hmax)
        out.append(f'<rect x="{x}" y="{base-h}" width="{bw}" height="{h}" fill="{color}"/>')
        if windows:
            for wy in range(base - h + 10, base - 8, 14):
                for wx in range(x + 6, x + bw - 8, 12):
                    if r.random() < 0.28:
                        out.append(f'<rect x="{wx}" y="{wy}" width="5" height="7" fill="{windows}" opacity="{r.uniform(.5,1):.2f}"/>')
        x += bw + r.randint(0, 6)
    return "".join(out)


def stars(n, w, h, seed=3, color="#fff"):
    import random
    r = random.Random(seed)
    return "".join(
        f'<circle cx="{r.uniform(0,w):.0f}" cy="{r.uniform(0,h):.0f}" r="{r.choice([.6,.8,1,1.3]):.1f}" fill="{color}" opacity="{r.uniform(.4,1):.2f}"/>'
        for _ in range(n)
    )


